import * as assert from 'node:assert/strict';
import * as vscode from 'vscode';
import { configure, documentText, fake, repo, review, row, sidebar, waitFor } from './harness.js';

const lines = (n: number) => Array.from({ length: n }, (_, i) => `line ${i + 1}`).join('\n') + '\n';

const LOCK = '{\n  "lockfileVersion": 3\n}\n';
const BASE = { 'src/a.ts': lines(5), 'src/b.ts': lines(5), 'package-lock.json': LOCK };
const EDITED = {
  'src/a.ts': lines(5).replace('line 3', 'line 3 edited'),
  'src/b.ts': lines(5).replace('line 3', 'line 3 edited'),
  'package-lock.json': LOCK.replace('3\n', '3,\n  "x": 1\n'),
};

/** Whether `path` was classified as generated, and so left out of the reading. */
const scaffolding = async (path: string) => {
  const api = await review();
  return api.host.active?.files.find((f) => f.path === path)?.hunks.every((h) => h.scaffolding !== undefined);
};

suite('scaffolding', () => {
  let undo: (() => Promise<void>) | undefined;

  setup(async () => {
    fake.reset();
    undo = await configure({ 'ai.enabled': false });
    await repo.reset(BASE);
    repo.write(EDITED);
  });

  teardown(async () => {
    await undo?.();
  });

  test('lockfiles go into a trailing collapsed cohort that progress does not count', async () => {
    await repo.reset({ ...BASE, 'yarn.lock': 'a\n' });
    repo.write({ ...EDITED, 'yarn.lock': 'b\n' });
    const api = await review();

    const last = api.host.active!.cohorts.at(-1)!;
    assert.equal(last.kind, 'scaffolding');
    assert.deepEqual(last.layers.map((l) => l.paths[0]), ['package-lock.json', 'yarn.lock']);
    const { item } = await row(/^Scaffolding · 2 files$/);
    assert.equal(item.collapsibleState, vscode.TreeItemCollapsibleState.Collapsed);
    assert.deepEqual(api.nav.progress, { reviewed: 0, total: 2 });
  });

  test('a file that says it is generated is scaffolding', async () => {
    await repo.reset({ ...BASE, 'src/schema.ts': '// @generated by protoc. Do not edit.\n' + lines(5) });
    repo.write({ 'src/schema.ts': '// @generated by protoc. Do not edit.\n' + lines(5).replace('line 3', 'line 3 edited') });

    assert.equal(await scaffolding('src/schema.ts'), true);
  });

  test('a path marked linguist-generated in .gitattributes is scaffolding', async () => {
    await repo.reset({ ...BASE, '.gitattributes': 'gen/** linguist-generated\n', 'gen/api.ts': lines(5) });
    repo.write({ 'gen/api.ts': lines(5).replace('line 3', 'line 3 edited') });

    assert.equal(await scaffolding('gen/api.ts'), true);
  });

  test('jury.scaffolding.patterns adds paths, and ! forces one back into the review', async () => {
    await repo.reset({ ...BASE, 'fixtures/data.json': '{}\n' });
    repo.write({ ...EDITED, 'fixtures/data.json': '{ "a": 1 }\n' });
    const restore = await configure({ 'scaffolding.patterns': ['fixtures/**', '!package-lock.json'] });
    try {
      assert.equal(await scaffolding('fixtures/data.json'), true);
      assert.equal(await scaffolding('package-lock.json'), false);
    } finally {
      await restore();
    }
  });

  test('with jury.scaffolding.mode off nothing is classified', async () => {
    const restore = await configure({ 'scaffolding.mode': 'off' });
    try {
      const api = await review();
      assert.ok(!api.host.active!.cohorts.some((c) => c.kind === 'scaffolding'));
      assert.equal(api.nav.progress.total, 3);
    } finally {
      await restore();
    }
  });

  test('with jury.scaffolding.mode inline generated files are classified but stay in the reading order', async () => {
    const restore = await configure({ 'scaffolding.mode': 'inline' });
    try {
      const api = await review();
      const lock = api.host.active!.files.find((f) => f.path === 'package-lock.json')!;
      assert.ok(lock.hunks.every((h) => h.scaffolding), 'still classified');
      assert.ok(!api.host.active!.cohorts.some((c) => c.kind === 'scaffolding'), 'no trailing scaffolding cohort');
    } finally {
      await restore();
    }
  });

  test('stepping through the review never lands on scaffolding', async () => {
    const api = await review();

    const visited: string[] = [];
    for (let i = 0; i < 4; i++) {
      await vscode.commands.executeCommand('jury.nextHunk');
      visited.push(api.nav.current!.file.path);
    }

    assert.deepEqual(visited, ['src/a.ts', 'src/b.ts', 'src/b.ts', 'src/b.ts']);
  });

  test('Not Scaffolding puts the file in the review and is remembered', async () => {
    const api = await review();

    await vscode.commands.executeCommand('jury.notScaffolding', (await row(/^Scaffolding/)).node);

    assert.doesNotMatch(await sidebar(), /Scaffolding/);
    assert.match(await sidebar(), /package-lock\.json/);
    assert.equal(api.nav.progress.total, 3);

    await vscode.commands.executeCommand('jury.close');
    await review();
    assert.equal(api.nav.progress.total, 3, 'still in the review after reopening');
  });

  test("Not Scaffolding keeps the model's grouping and adds the file just before the scaffolding", async () => {
    await repo.reset({ ...BASE, 'src/c.ts': lines(5), 'yarn.lock': 'a\n' });
    repo.write({ ...EDITED, 'src/c.ts': lines(5).replace('line 3', 'line 3 edited'), 'yarn.lock': 'b\n' });
    await undo?.();
    undo = undefined;
    const api = await review('jury.review', { clustered: true });

    const lock = api.host.active!.cohorts.at(-1)!.layers.find((l) => l.paths[0] === 'package-lock.json')!;
    await vscode.commands.executeCommand('jury.notScaffolding', {
      type: 'layer',
      cohortIndex: api.host.active!.cohorts.length - 1,
      layerIndex: 0,
      cohort: api.host.active!.cohorts.at(-1),
      layer: lock,
    });

    const titles = api.host.active!.cohorts.map((c) => c.title);
    assert.deepEqual(titles.slice(0, 2), ['Fake cohort 1', 'Fake cohort 2']);
    assert.match(titles[2]!, /package-lock\.json/);
    assert.equal(titles[3], 'Scaffolding · 1 file');
  });

  test('the export says how many generated files were not reviewed', async () => {
    await review();

    void vscode.commands.executeCommand('jury.export');

    await waitFor(
      () => /_1 generated files? (was|were) not reviewed: Generated or vendored: /.test(documentText('Review.md')),
      'the generated files in the export',
    );
  });
});
